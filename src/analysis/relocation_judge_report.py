"""Summarize the LLM-judge labels of the sampled events and check them
against human labels (RQ2).

Motivation: two independent LLM judges (same rubric, blind to each other and
to the model that wrote the code) labeled every sampled event, and a third
judge settled disagreements. LLM labels are only usable if they agree with
people, so this script also draws a random subset for two human annotators
and, once their labels are filled in, reports the agreement.

Inputs:  results/finding_tracking/relocation_judge.json (judge labels)
         results/finding_tracking/relocation_sample_context.json
         results/finding_tracking/relocation_human_check.csv (if labeled)
Outputs: results/finding_tracking/relocation_judge.md
         results/finding_tracking/relocation_human_check.{csv,md} (first run)

Usage:
    python -m src.analysis.relocation_judge_report [--human-n 30] [--seed 2027]
"""
from __future__ import annotations

import argparse
import csv
import json
import random
from collections import Counter

from src.analysis.relocation import OUT

LABELS = ["SAME", "FIX+NEW", "BENIGN", "UNCLEAR"]


def kappa(a: list[str], b: list[str]) -> float | None:
    """Cohen's kappa for two label lists of equal length."""
    n = len(a)
    if not n:
        return None
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(a) | set(b)) / (n * n)
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)


def write_human_sheet(events: list[dict], context: dict, n: int, seed: int) -> None:
    ids = sorted(random.Random(seed).sample([e["id"] for e in events], n))
    with open(OUT / "relocation_human_check.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "label_a", "label_b", "notes"])
        w.writerows([[i, "", "", ""] for i in ids])
    md = ["# Human check of the LLM-judge labels", "",
          f"{n} events drawn at random (seed {seed}). Label each one in "
          "relocation_human_check.csv BEFORE looking at relocation_judge.md. "
          "Labels: SAME (the weakness moved and persists), FIX+NEW (the old "
          "weakness is gone; what is flagged now is a different or safe "
          "operation), BENIGN (both locations are safe; the analyzer flags a "
          "pattern), UNCLEAR. Assume standard C contracts (strings are "
          "NUL-terminated, sizes passed by callers are correct) unless the "
          "program itself breaks them.", ""]
    for i in ids:
        c = context[i]
        md += [f"## {i}  `{c['rule']}`  round {c['round'] - 1} -> {c['round']}", "",
               f"Task: {c['task']}", "",
               f"Left `{', '.join(c['left_functions'])}`, entered "
               f"`{', '.join(c['entered_functions'])}`.", "",
               "Reports before: " + "; ".join(c["before_reports"]), "",
               "Reports after: " + "; ".join(c["after_reports"]), "",
               "Before:", "", "```c", c["before_source"], "```", "",
               "After:", "", "```c", c["after_source"], "```", ""]
    (OUT / "relocation_human_check.md").write_text("\n".join(md) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--human-n", type=int, default=30)
    ap.add_argument("--seed", type=int, default=2027)
    a = ap.parse_args()
    events = json.loads((OUT / "relocation_judge.json").read_text())
    context = {c["id"]: c for c in
               json.loads((OUT / "relocation_sample_context.json").read_text())}
    sheet = OUT / "relocation_human_check.csv"
    if not sheet.is_file():
        write_human_sheet(events, context, a.human_n, a.seed)

    final = {e["id"]: e["final"] for e in events if e["final"]}
    j1 = [e["judge1"]["label"] for e in events if e["judge1"] and e["judge2"]]
    j2 = [e["judge2"]["label"] for e in events if e["judge1"] and e["judge2"]]
    labels = Counter(f["label"] for f in final.values())
    lines = ["# LLM-judge labels of the sampled relocation events", "",
             f"{len(events)} events; two independent judges with the same rubric, "
             "a third judge for disagreements. Generated by "
             "`python -m src.analysis.relocation_judge_report`.", "",
             "| Label | Events |", "|---|---:|"]
    lines += [f"| {k} | {labels[k]} ({100 * labels[k] / len(final):.1f}%) |" for k in LABELS]
    agree = sum(x == y for x, y in zip(j1, j2))
    k = kappa(j1, j2)
    lines += ["", f"Judge 1 vs judge 2: {agree}/{len(j1)} identical labels, "
              f"Cohen's kappa {k:.2f}. Both judges are the same model with the "
              "same rubric, so this agreement is an upper bound; the human "
              "check below is the real test.", ""]
    for facet in ("old_unsafe", "new_unsafe", "same_operation"):
        c = Counter(f[facet] for f in final.values())
        lines.append(f"- {facet}: " + ", ".join(f"{v} {n}" for v, n in sorted(c.items())))
    lines += ["", "## Events not labeled BENIGN", ""]
    for i, f in sorted(final.items()):
        if f["label"] != "BENIGN":
            lines.append(f"- {i} ({context[i]['rule']}): {f['label']}. {f['rationale']}")

    with open(sheet) as fh:
        human = [r for r in csv.DictReader(fh) if r["label_a"] and r["label_b"]]
    lines += ["", "## Human check", ""]
    if not human:
        lines.append("Not labeled yet (relocation_human_check.csv).")
    else:
        ha = [r["label_a"].strip().upper() for r in human]
        hb = [r["label_b"].strip().upper() for r in human]
        lj = [final[r["id"]]["label"] for r in human]
        lines += [f"{len(human)} events labeled by two people.",
                  f"- human A vs human B: kappa {kappa(ha, hb):.2f}",
                  f"- judge vs human A: kappa {kappa(lj, ha):.2f}",
                  f"- judge vs human B: kappa {kappa(lj, hb):.2f}"]
    (OUT / "relocation_judge.md").write_text("\n".join(lines) + "\n")
    print(f"written -> {OUT / 'relocation_judge.md'}")


if __name__ == "__main__":
    main()
